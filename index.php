        // 定义温馨暖色调颜色数组
        const warmColors = [
            "#FFCDB2", "#FFB7B2", "#FFA8A8",    
            "#FFD166", "#FFC685", "#FFB76E",    
            "#C5C1FF", "#D4C9FF", "#E0B0FF",    
            "#98D7C2", "#A7E3D0", "#B5F0DD",    
            "#FF9FB1", "#FFB6C1", "#FFCDD5",    
            "#FFD6A2", "#FFE0B2", "#FFF0CD"     
        ];

        // 生成随机温馨三色调渐变
        function createWarmGradient() {
            const colors = [];
            while (colors.length < 3) {
                const color = warmColors[Math.floor(Math.random() * warmColors.length)];
                if (!colors.includes(color)) colors.push(color);
            }
            return `linear-gradient(-225deg, ${colors[0]} 0%, ${colors[1]} 50%, ${colors[2]} 100%)`;
        }

        // 应用随机渐变到页面
        const gradientStyle = createWarmGradient();
        document.documentElement.style.setProperty('--icon-gradient', gradientStyle);
        document.documentElement.style.setProperty('--button-gradient', gradientStyle);
        document.documentElement.style.setProperty('--primary-color', warmColors[Math.floor(Math.random() * warmColors.length)]);
        
        // 定义接口地址
        const apiUrl = 'https://kjuuggfdrrg4455.github.io/automatic-dollop/index.htm?hx=';
        function getUrl(){
            const targetUrl = document.getElementById('targetUrl').value;
            const btn = document.getElementById('generateButton');
            
            if (!targetUrl) {
                // 添加输入框抖动效果
                const inputWrapper = document.querySelector('.input-wrapper');
                inputWrapper.style.animation = 'shake 0.5s';
                setTimeout(() => {
                    inputWrapper.style.animation = '';
                }, 500);
                return;
            }
            
            btn.value = "生成中..."; 
            btn.disabled = true;

            // 使用base64编码URL
            const encodedUrl = btoa(targetUrl);
            const shortUrl = apiUrl + encodedUrl;
            
            setTimeout(function(){
                document.getElementById('resultContainer').innerHTML =
                `<div class='short-url-display' id='shortUrlDisplay' onclick='copyShortLink("${shortUrl}")'>${shortUrl}</div>`;
                
                // 添加结果出现的动画
                const result = document.getElementById('shortUrlDisplay');
                result.style.animation = 'bounceIn 0.6s';
                
                btn.value = "生成"; 
                btn.disabled = false;
            }, 1000);
        }
        
        function copyShortLink(url){
            const textarea = document.createElement('textarea');
            textarea.value = url;
            textarea.style.position = 'fixed';
            textarea.style.opacity = '0';
            document.body.appendChild(textarea);
            textarea.select();
            try {
                const successful = document.execCommand('copy');
                const msg = successful ? '链接已成功复制到剪贴板' : '复制链接失败，请重试';
                
                // 添加复制成功反馈动画
                const display = document.getElementById('shortUrlDisplay');
                display.style.animation = 'pulse 0.5s';
                setTimeout(() => {
                    display.style.animation = '';
                }, 500);
                
                alert(msg);
            } catch(err) {
                alert('复制链接失败，请重试');
            }
            document.body.removeChild(textarea);
        }
        
